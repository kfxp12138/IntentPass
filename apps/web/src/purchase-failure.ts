const codes=new Set([
  'AUTHORIZATION_EXPIRED','AUTHORIZATION_CHAIN_BLOCKED','SESSION_CHANGED',
  'PURCHASE_CONTEXT_CHANGED','WALLET_SIGNATURE_PENDING','WALLET_OWNER_UNAVAILABLE',
  'WALLET_OWNER_MISMATCH','WALLET_CHAIN_MISMATCH','WALLET_FRAME_UNAVAILABLE',
  'WALLET_FRAME_INVALID','WALLET_CONFIGURATION_REQUIRED','WALLET_CONNECTION_UNAVAILABLE',
  'WALLET_CONNECTION_RESPONSE_INVALID','WALLET_OWNER_SIGNATURE_INVALID',
  'WALLET_SIGNATURE_OUTCOME_UNKNOWN','WALLET_SIGNATURE_CANCELLED_OR_UNAVAILABLE',
  'WALLET_SIGNATURE_NOT_REQUESTED','WALLET_GRANT_DEPLOYMENT_MISMATCH',
  'ORIGINAL_AUTHORIZATION_OUTCOME_UNKNOWN','PASSKEY_CANCELLED','PASSKEY_UNAVAILABLE',
  'PRF_UNSUPPORTED','RPID_MISMATCH','SECURE_CONTEXT_REQUIRED','CAPSULE_AUTH_FAILED',
  'CAPSULE_UPLOAD_OUTCOME_UNKNOWN','PROPOSAL_OUTCOME_RECONCILIATION_REQUIRED',
  'AUTOMATION_CONFIRMATION_PENDING','AUTOMATION_ORIGINAL_OUTCOME_UNRESOLVED',
  'PREPARED_KEY_EXPIRED','PREPARED_KEY_CONTEXT_MISMATCH',
]);
/** Never surface provider exception messages, tokens, payloads or nested causes. */
export function purchaseFailureCode(error:unknown){
  return error instanceof Error&&codes.has(error.message)?error.message:'PURCHASE_OPERATION_UNAVAILABLE';
}
export function automaticFailureFeedback(error:unknown,message:string){
  return `自动推进已停止。${message} 故障编号：${purchaseFailureCode(error)}。`;
}
